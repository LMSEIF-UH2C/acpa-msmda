options(digits=17)
emit <- function(key,value) cat(key,format(as.numeric(value),digits=17,scientific=TRUE),sep="\t",fill=TRUE)
a <- matrix(c(1,2,4,2,4,5,3,4,7,4,6,8),ncol=3,byrow=TRUE)
b <- matrix(c(2,4,6,3,7,8,5,10,11,6,10,13),ncol=3,byrow=TRUE)
x <- 1:8
m <- c(1,4,2,5,3,8,6,7)
y <- c(3,5,4,9,8,14,11,15)
p <- t.test(a[,2],a[,1],paired=TRUE)
emit("paired_t",p$statistic);emit("paired_p",p$p.value)
emit("paired_ci_low",p$conf.int[1]);emit("paired_ci_high",p$conf.int[2])
w <- t.test(a[,3],b[,3])
emit("welch_t",w$statistic);emit("welch_df",w$parameter);emit("welch_p",w$p.value)
pc <- cor.test(x,y,method="pearson")
sp <- cor.test(x,y,method="spearman",exact=FALSE)
emit("pearson_r",pc$estimate);emit("pearson_p",pc$p.value)
emit("spearman_r",sp$estimate);emit("spearman_p",sp$p.value)
fr <- friedman.test(a)
emit("friedman_chi2",fr$statistic);emit("friedman_p",fr$p.value)
d <- data.frame(value=c(a[,3],b[,3]),group=factor(rep(1:2,each=4)))
ow <- summary(aov(value~group,d))[[1]]
emit("oneway_F",ow[1,"F value"]);emit("oneway_p",ow[1,"Pr(>F)"])
long <- function(z,groups) data.frame(value=as.vector(t(z)),id=factor(rep(seq_len(nrow(z)),each=ncol(z))),time=factor(rep(seq_len(ncol(z)),nrow(z))),group=factor(rep(groups,each=ncol(z))))
rm <- summary(aov(value~time+Error(id/time),long(a,rep(1,4))))
tab <- rm[["Error: id:time"]][[1]]
rownames(tab)<-trimws(rownames(tab))
emit("rm_F",tab["time","F value"]);emit("rm_p",tab["time","Pr(>F)"])
mx <- summary(aov(value~group*time+Error(id/time),long(rbind(a,b),rep(1:2,each=4))))
between <- mx[["Error: id"]][[1]]
within <- mx[["Error: id:time"]][[1]]
# aov row names can include trailing spaces.
rownames(between)<-trimws(rownames(between));rownames(within)<-trimws(rownames(within))
emit("mixed_group_F",between["group","F value"])
emit("mixed_time_F",within["time","F value"])
emit("mixed_interaction_F",within["group:time","F value"])
emit("mixed_interaction_p",within["group:time","Pr(>F)"])
fit <- summary(lm(y~I(x-mean(x))*I(m-mean(m))))
emit("moderation_b",fit$coefficients[4,1]);emit("moderation_se",fit$coefficients[4,2])
emit("moderation_p",fit$coefficients[4,4]);emit("moderation_r2",fit$r.squared);emit("moderation_F",fit$fstatistic[1])
pairs <- combn(3,2)
pv <- apply(pairs,2,function(i)t.test(a[,i[2]],a[,i[1]],paired=TRUE)$p.value)
for(i in seq_along(pv)) emit(paste0("holm_",i-1),p.adjust(pv,"holm")[i])
