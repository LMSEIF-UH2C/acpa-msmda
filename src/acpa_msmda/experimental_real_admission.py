"""A5 restricted real evidence admission; never relabel a fixture as real.

A pinned, operator-approved manifest is a trust boundary, not proof of external
validity. The caller must obtain approval and pin its bytes outside the manifest.
No manifest or approval is generated by this module. No public UI activation.
"""
from datetime import date
from hashlib import sha256
from itertools import combinations
from pathlib import Path
import json
from .experimental_qualification import canonical
from .experimental_ecosystem import GATES, _context, _functions, _resource_reason, _solve, inspect_documentary_register

def _digest(value):
    return sha256(canonical(value).encode("utf-8")).hexdigest()

def _day(s):
    if not isinstance(s,str) or date.fromisoformat(s).isoformat()!=s:
        raise ValueError("Invalid date")
    return s

def context_digest(context, scenario):
    _context(context)
    if not isinstance(scenario,dict) or set(scenario)!={"id","platform","data_policy","setting"} or any(not isinstance(v,str) or not v.strip() for v in scenario.values()):
        raise ValueError("Exact scenario required")
    normalized={**context,"required":sorted(context["required"]),"optional":sorted(context["optional"])}
    return _digest({"context":normalized,"scenario":scenario})

def _review_valid(row, expected_context, as_of):
    return (row.get("review_status")=="OWNER_APPROVED_INTERNAL"
            and row.get("context_sha256")==expected_context
            and isinstance(row.get("decision_ref"),str) and bool(row["decision_ref"].strip())
            and _day(row.get("reviewed_on"))<=as_of<=_day(row.get("valid_until")))

def _proofs_valid(proofs, keys):
    if not isinstance(proofs,dict) or set(proofs)!=set(keys):
        return False
    for entries in proofs.values():
        if not isinstance(entries,list) or not entries:
            return False
        for e in entries:
            if not isinstance(e,dict) or set(e)!={"kind","locator","finding"}:
                return False
            if e["kind"] not in {"OFFICIAL_DOCUMENTATION","ACTUAL_TEST","OWNER_CONTEXT_CONFIRMATION"}:
                return False
            if not all(isinstance(e[k],str) and e[k].strip() for k in ("locator","finding")):
                return False
    return True

def evaluate_real(db_path, context, scenario, *, manifest_path=None,
                  approved_sha256=None, as_of, max_combinations=10000):
    """Return internal candidate configurations only from a separately pinned manifest.

    Structural and lineage checks do not authenticate the factual assertions.
    The decision reference and approved digest must come from authorized
    operational configuration, not a user-uploaded file or UI text.
    """
    as_of=_day(as_of)
    context_hash=context_digest(context,scenario)
    audit=inspect_documentary_register(db_path,context)
    out={"mode":"REAL_INTERNAL_REVIEW_ONLY","status":"NO_APPROVED_MANIFEST",
         "records":audit["records"],"admitted":0,"recommended":[],"selected":None,
         "coverage_assessed":False,"context_sha256":context_hash,"diagnostics":{},
         "limitation":"INTERNAL_CONTEXT_REVIEW_NOT_EXTERNAL_VALIDATION"}
    if manifest_path is None or approved_sha256 is None:
        return out
    raw=Path(manifest_path).read_bytes()
    if sha256(raw).hexdigest()!=approved_sha256:
        out["status"]="APPROVED_DIGEST_MISMATCH"
        return out
    manifest=json.loads(raw)
    if not isinstance(manifest,dict) or set(manifest)!={"schema_version","records","pairs"} or manifest["schema_version"]!=1 or not isinstance(manifest["records"],list) or not isinstance(manifest["pairs"],list):
        raise ValueError("Invalid review manifest")
    current={d["id"]:d for d in audit["diagnostics"]}
    pool=[]
    seen=set()
    required_fields={"id","source_observation","qualification_observation","review_status",
                     "context_sha256","decision_ref","reviewed_on","valid_until",
                     "candidate","proofs"}
    for row in manifest["records"]:
        if not isinstance(row,dict) or set(row)!=required_fields or not isinstance(row.get("id"),str) or row["id"] in seen:
            raise ValueError("Invalid or duplicate review")
        key=row["id"]; seen.add(key); d=current.get(key); t=row["candidate"]
        reason=None
        if d is None or d["status"]!="DOCUMENTARY_PROPOSAL_ONLY" or row["source_observation"]!=d["source_observation"] or row["qualification_observation"]!=d["qualification_observation"]:
            reason="STALE_OR_UNLINKED_OBSERVATION"
        elif not _review_valid(row,context_hash,as_of):
            reason="REVIEW_NOT_CURRENT_OR_NOT_AUTHORIZED"
        elif not isinstance(t,dict) or set(t)!={"id","product","functions","gates","offline","cost","currency","period","load","device_slots","requires","incompatible"} or t.get("id")!=key:
            reason="INVALID_REAL_CANDIDATE"
        else:
            try:
                functions=_functions(t["functions"])
                keys={"function:"+f for f in functions}|{"gate:"+g for g in GATES}|{"cost","load","device_slots","relations","offline"}
                if not _proofs_valid(row["proofs"],keys):
                    reason="MISSING_CLAIM_EVIDENCE"
                else:
                    reason=_resource_reason(t,context)
            except (ValueError,TypeError,KeyError):
                reason="INVALID_REAL_CANDIDATE"
        out["diagnostics"][key]=reason or "ADMITTED_INTERNAL"
        if reason is None:
            pool.append(t)
    pair_fields={"ids","context_sha256","decision_ref","review_status","reviewed_on","valid_until","transfer","proofs"}
    pairs={}
    for p in manifest["pairs"]:
        if not isinstance(p,dict) or set(p)!=pair_fields or not isinstance(p.get("ids"),list) or len(p["ids"])!=2 or not all(isinstance(x,str) for x in p["ids"]) or len(set(p["ids"]))!=2:
            raise ValueError("Invalid pair review")
        key=tuple(sorted(p["ids"]))
        if key in pairs or not set(key)<=seen:
            raise ValueError("Duplicate or unknown pair")
        pairs[key]=(_review_valid(p,context_hash,as_of)
                    and p["transfer"] in {"NO_TRANSFER_REQUIRED","MANUAL_TRANSFER_TESTED"}
                    and _proofs_valid(p["proofs"],{"pair_compatibility","transfer"}))
    def pair_reason(items):
        if any(not pairs.get(tuple(sorted((a["id"],b["id"]))),False) for a,b in combinations(items,2)):
            return "PAIR_COMPATIBILITY_NOT_ESTABLISHED"
        return None
    result=_solve(context,pool,max_combinations=max_combinations,reason_fn=_resource_reason,
                  pair_fn=pair_reason,mode="REAL_INTERNAL_REVIEW_ONLY",complete_status="COMPLETE_INTERNAL_CONFIGURATION")
    out.update(result)
    out["admitted"]=len(pool)
    out["coverage_assessed"]=bool(pool) and result["status"] not in {"INCOMPLETE_SEARCH","UNSUPPORTED_REQUIREMENT"}
    # Never imply coverage of an unassessed catalogue or promote partial outputs.
    if result["selected"] is not None:
        out["recommended"]=result["selected"]["ids"]
    else:
        out["recommended"]=[]
    if not pool and result["status"]=="NO_COMPLETE_SET":
        out["status"]="NO_ADMISSIBLE_REAL_CANDIDATE"
        out["uncovered_required"]=None
    out["manifest_sha256"]=approved_sha256
    return out
